#!/usr/bin/env python3
"""Regenerate the acceptance-coverage table in docs/acceptance-coverage.md.

Scans every Rust source for references to RFC 0001 §16's acceptance ids
(A01..A38, case-insensitive, so `a08_concurrent_...` test names count) and
rewrites the table between the AUTOGENERATED markers. Run from the repo root:

    python3 scripts/acceptance_coverage.py
"""

import pathlib
import re
import sys

ROOTS = ["crates", "services", "cli", "apps", "tests"]
SPEC = pathlib.Path("spec/rfc-0001-open-institutional-custody.md")
DOC = pathlib.Path("docs/acceptance-coverage.md")
BEGIN = "<!-- AUTOGENERATED by scripts/acceptance_coverage.py; edit the script, not the table. -->"
END = "<!-- /AUTOGENERATED -->"

# A reference is `a` or `A` + two digits, not embedded in a longer
# alphanumeric token; a trailing `_` (test names) still counts.
REF = re.compile(r"(?<![A-Za-z0-9])[Aa]([0-3][0-9])(?![0-9])")


def main() -> int:
    spec = SPEC.read_text()
    rows = {m.group(1): m.group(2).strip() for m in re.finditer(r"\| (A\d\d) \| ([^|]+) \|", spec)}
    if len(rows) != 38:
        sys.exit(f"expected 38 acceptance rows in {SPEC}, found {len(rows)}")
    refs: dict[str, set[str]] = {}
    for root in ROOTS:
        for path in pathlib.Path(root).rglob("*.rs"):
            for m in REF.finditer(path.read_text(errors="ignore")):
                aid = "A" + m.group(1)
                if aid in rows:
                    refs.setdefault(aid, set()).add(str(path))
    lines = [BEGIN, "", "| Id | Scenario | Referenced in |", "| --- | --- | --- |"]
    for aid in sorted(rows):
        files = refs.get(aid)
        where = "<br>".join(f"`{f}`" for f in sorted(files)) if files else "**no reference**"
        lines.append(f"| {aid} | {rows[aid]} | {where} |")
    lines += ["", f"{len(refs)} of {len(rows)} ids are referenced.", "", END]
    doc = DOC.read_text()
    pattern = re.compile(re.escape(BEGIN) + ".*" + re.escape(END), re.DOTALL)
    if not pattern.search(doc):
        sys.exit(f"{DOC} has no AUTOGENERATED markers")
    DOC.write_text(pattern.sub("\n".join(lines), doc))
    print(f"{DOC}: {len(refs)} of {len(rows)} ids referenced")
    return 0


if __name__ == "__main__":
    sys.exit(main())
